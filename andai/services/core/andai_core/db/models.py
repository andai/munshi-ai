def _in(column: str, values: tuple[str, ...]) -> str:
    return f"{column} IN ({', '.join(repr(v) for v in values)})"


def _not_terminal() -> str:
    return f"status NOT IN ({', '.join(repr(v) for v in TERMINAL_STATUSES)})"


def _live() -> str:
    """A meeting the bot is in or on its way to: neither over nor only scheduled (0015)."""
    return f"status NOT IN ({', '.join(repr(v) for v in (*TERMINAL_STATUSES, 'scheduled'))})"


def _uuid_pk() -> Mapped[uuid.UUID]:
    return mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        server_default=text("gen_random_uuid()"),
    )


def _created_at() -> Mapped[datetime]:
    return mapped_column(DateTime(timezone=True), nullable=False, server_default=func.now())


# The stored whole-word form of a folded search text (migration 0008).
SEARCH_TSV = "to_tsvector('simple'::regconfig, search_text)"


def _trigram_index(table: str, column: str) -> Index:
    """Spelling-variant index of a folded text column (migration 0008)."""
    return Index(
        f"ix_{table}_{column}_trgm",
        column,
        postgresql_using="gin",
        postgresql_ops={column: "gin_trgm_ops"},
    )


